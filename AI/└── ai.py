# =========================
# ذخیره حافظه داخل همین فایل
# =========================

FILE_NAME = os.path.abspath(__file__)


def save_memory():
    with open(FILE_NAME, "r", encoding="utf-8") as f:
        code = f.read()

    start = code.index("memory = {")
    end = code.index("\n}\n\n# =========================", start) + 2

    new_memory = "memory = " + json.dumps(
        memory,
        ensure_ascii=False,
        indent=4
    )

    new_code = code[:start] + new_memory + code[end:]

    with open(FILE_NAME, "w", encoding="utf-8") as f:
        f.write(new_code)


# =========================
# پیدا کردن بهترین پاسخ
# =========================

def get_answer(message):
    message = message.strip()

    # پاسخ دقیق
    if message in memory:
        return memory[message]

    # پیدا کردن سؤال مشابه
    questions = list(memory.keys())

    matches = difflib.get_close_matches(
        message,
        questions,
        n=1,
        cutoff=0.65
    )

    if matches:
        return memory[matches[0]]

    return None



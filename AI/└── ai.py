def check_image(message):
    extensions = (
        ".jpg",
        ".jpeg",
        ".png",
        ".webp",
        ".gif"
    )

    if message.lower().endswith(extensions):
        if os.path.exists(message):
            return "عکس دریافت شد! 🖼️"
        else:
            return "مسیر عکس پیدا نشد."


